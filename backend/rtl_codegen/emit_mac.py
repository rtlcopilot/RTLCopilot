

from __future__ import annotations


def emit_mac(
    instance_name:   str,
    data_width:      int = 8,
    acc_width:       int = 32,
    pipeline_stages: int = 1,
) -> tuple[str, str]:
    """
    Emit a standalone MAC module.

    Returns:
        (module_name, verilog_source)  - ready to write as  mac_<name>.v
    """
    if pipeline_stages not in (0, 1):
        pipeline_stages = 1

    module_name = f"mac_{instance_name}"
    prod_width  = data_width * 2

    lines: list[str] = []

    lines += [
        f"// MAC (Multiply-Accumulate) - generated by RTLCopilot emit_mac.py",
        f"// DATA_WIDTH={data_width}  ACC_WIDTH={acc_width}  PIPELINE_STAGES={pipeline_stages}",
        f"",
        f"module {module_name} #(",
        f"    parameter DATA_WIDTH      = {data_width},",
        f"    parameter ACC_WIDTH       = {acc_width},",
        f"    parameter PIPELINE_STAGES = {pipeline_stages}",
        f") (",
        f"    input  wire                   clk,",
        f"    input  wire                   rst,",
        f"    input  wire                   en,",
        f"    input  wire                   clear,",
        f"    input  wire [DATA_WIDTH-1:0]  a,",
        f"    input  wire [DATA_WIDTH-1:0]  b,",
        f"    output reg  [ACC_WIDTH-1:0]   result,",
        f"    output reg                    overflow",
        f");",
        f"",
    ]

    if pipeline_stages == 0:
        # Combinational multiply, registered accumulate (1-cycle latency)
        pad_bits = acc_width - prod_width
        lines += [
            f"    // -- Combinational multiply ----------------------------------",
            f"    wire [{prod_width}-1:0] product;",
            f"    assign product = a * b;",
            f"",
            f"    wire [ACC_WIDTH-1:0] product_ext;",
            "    assign product_ext = {" + f"{{{pad_bits}{{1'b0}}}}, product" + "};",
            f"",
            f"    wire [ACC_WIDTH:0] sum_full;",
            "    assign sum_full = {1'b0, result} + {1'b0, product_ext};",
            f"",
            f"    // -- Sequential accumulator ----------------------------------",
            f"    always @(posedge clk) begin",
            f"        if (rst) begin",
            f"            result   <= {acc_width}'b0;",
            f"            overflow <= 1'b0;",
            f"        end else if (clear) begin",
            f"            result   <= {acc_width}'b0;",
            f"            overflow <= 1'b0;",
            f"        end else if (en) begin",
            f"            result   <= sum_full[ACC_WIDTH-1:0];",
            f"            overflow <= overflow | sum_full[ACC_WIDTH];",
            f"        end",
            f"    end",
            f"",
        ]
    else:
        # Registered multiply then accumulate (2-cycle latency)
        pad_bits = acc_width - prod_width
        lines += [
            f"    // -- Stage 1: registered multiply ----------------------------",
            f"    reg [{prod_width}-1:0] product_reg;",
            f"    reg                    en_d1;",
            f"    reg                    clear_d1;",
            f"",
            f"    always @(posedge clk) begin",
            f"        if (rst) begin",
            f"            product_reg <= {prod_width}'b0;",
            f"            en_d1       <= 1'b0;",
            f"            clear_d1    <= 1'b0;",
            f"        end else begin",
            f"            product_reg <= a * b;",
            f"            en_d1       <= en;",
            f"            clear_d1    <= clear;",
            f"        end",
            f"    end",
            f"",
            f"    // -- Stage 2: accumulate -------------------------------------",
            f"    wire [ACC_WIDTH-1:0] product_ext;",
            "    assign product_ext = {" + f"{{{pad_bits}{{1'b0}}}}, product_reg" + "};",
            f"",
            f"    wire [ACC_WIDTH:0] sum_full;",
            "    assign sum_full = {1'b0, result} + {1'b0, product_ext};",
            f"",
            f"    always @(posedge clk) begin",
            f"        if (rst) begin",
            f"            result   <= {acc_width}'b0;",
            f"            overflow <= 1'b0;",
            f"        end else if (clear_d1) begin",
            f"            result   <= {acc_width}'b0;",
            f"            overflow <= 1'b0;",
            f"        end else if (en_d1) begin",
            f"            result   <= sum_full[ACC_WIDTH-1:0];",
            f"            overflow <= overflow | sum_full[ACC_WIDTH];",
            f"        end",
            f"    end",
            f"",
        ]

    lines += ["endmodule", ""]
    return module_name, "\n".join(lines)


def mac_instantiation(
    instance_name:  str,
    data_width:     int = 8,
    acc_width:      int = 32,
    pipeline_stages:int = 1,
    a_src:          str = "0",
    b_src:          str = "0",
    en_src:         str = "0",
    clear_src:      str = "1'b0",
    result_wire:    str = "",
    overflow_wire:  str = "",
) -> str:
    """Return the Verilog instantiation string for a mac_<instance_name> module."""
    module_name   = f"mac_{instance_name}"
    result_conn   = result_wire   if result_wire   else f"{instance_name}_result"
    overflow_conn = overflow_wire if overflow_wire else f"{instance_name}_overflow"

    return "\n".join([
        f"    {module_name} #(",
        f"        .DATA_WIDTH      ({data_width}),",
        f"        .ACC_WIDTH       ({acc_width}),",
        f"        .PIPELINE_STAGES ({pipeline_stages})",
        f"    ) {instance_name} (",
        f"        .clk     (clk),",
        f"        .rst     (rst),",
        f"        .en      ({en_src}),",
        f"        .clear   ({clear_src}),",
        f"        .a       ({a_src}),",
        f"        .b       ({b_src}),",
        f"        .result  ({result_conn}),",
        f"        .overflow({overflow_conn})",
        f"    );",
    ])