from __future__ import annotations

import math

# ---------------------------------------------------------------------------
# CORDIC vector rotation block
#
#   (x, y) rotated by 'angle'  ->  (x_out, y_out)
#
# Number formats (the tool converts decimals for the user):
#   x, y, x_out, y_out : value x 256       (3.5   -> 896)
#   angle              : degrees x 100     (30.25 -> 3025)   16 bit signed
#
# The CORDIC gain (1.647) is removed inside the block, so the length of the
# vector stays the same after rotation (no gain at the output).
# ---------------------------------------------------------------------------

# These numbers are fixed on purpose (the user does not choose them)
CORDIC_ITERATIONS  = 16     # number of rotation steps
CORDIC_ANGLE_BITS  = 6      # extra fractional bits kept for the angle
COORD_SCALE        = 256    # decimal -> integer scale for x and y
ANGLE_SCALE        = 100    # decimal -> integer scale for angle (degrees)


def _atan_table_lines() -> list[str]:
    """Build the 'case' lines of the arctan table:  atan(2^-i) in degrees x100 x64."""
    lines = []
    for i in range(CORDIC_ITERATIONS):
        degrees = math.degrees(math.atan(2.0 ** -i))
        value   = round(degrees * ANGLE_SCALE * (1 << CORDIC_ANGLE_BITS))
        lines.append(f"            {i}: atan_table = 24'sd{value};   // atan(2^-{i}) = {degrees:.4f} deg")
    return lines


def emit_cordic(
    instance_name: str,
    data_width:    int = 16,
) -> tuple[str, str]:
    """
    Emit a standalone CORDIC vector-rotation module.

    Returns:
        (module_name, verilog_source)  - ready to write as  cordic_<name>.v
    """
    module_name = f"cordic_{instance_name}"

    template = """// CORDIC vector rotation - generated by RTLCopilot emit_cordic.py
// Rotates the point (x, y) by 'angle' and gives (x_out, y_out).
// The CORDIC gain is already removed, so the vector length does not change.
//
//   x, y, x_out, y_out : signed, value x 256        (3.5   -> 896)
//   angle              : signed 16 bit, degrees x 100 (30.25 -> 3025)
//
// Valid angle  : -180.00 to +180.00 degrees
// Valid x, y   : keep sqrt(x*x + y*y) below 128 so the result fits
// Latency      : 1 clock (result is registered)

module __MODULE__ #(
    parameter DATA_WIDTH = __DW__
) (
    input  wire                         clk,
    input  wire                         rst,
    input  wire signed [DATA_WIDTH-1:0] x,
    input  wire signed [DATA_WIDTH-1:0] y,
    input  wire signed [15:0]           angle,
    output reg  signed [DATA_WIDTH-1:0] x_out,
    output reg  signed [DATA_WIDTH-1:0] y_out
);

    // -- fixed settings ------------------------------------------------
    localparam ITER  = __ITER__;                    // number of rotation steps
    localparam GUARD = 4;                           // extra bits for x and y
    localparam W     = DATA_WIDTH + GUARD + 2;      // width used inside
    localparam signed [17:0] K_INV = 18'sd39797;    // 1/gain = 0.60725 * 65536
    localparam ROUND = 1 << (15 + GUARD);           // for rounding at the end

    // -- arctan table: atan(2^-i) in degrees x 100 x 64 -----------------
    function signed [23:0] atan_table;
        input integer i;
        begin
            case (i)
__TABLE__
            default: atan_table = 24'sd0;
            endcase
        end
    endfunction

    // -- working variables ------------------------------------------------
    reg signed [DATA_WIDTH:0]   xs, ys;       // x, y after the 90 degree fix
    reg signed [23:0]           z;            // angle left to rotate (x64)
    reg signed [W-1:0]          xt, yt;       // running x, y
    reg signed [W-1:0]          xn, yn;       // next x, y
    reg signed [W+17:0]         px, py;       // after gain removal
    reg signed [DATA_WIDTH-1:0] x_next, y_next;
    integer i;

    // -- rotation (combinational) -----------------------------------------
    always @(*) begin
        // Step 1: CORDIC only works up to about 99 degrees.
        //         For bigger angles first turn the point by 90 degrees.
        if (angle > 9000) begin
            xs = -y;
            ys = x;
            z  = angle - 9000;
        end else if (angle < -9000) begin
            xs = y;
            ys = -x;
            z  = angle + 9000;
        end else begin
            xs = x;
            ys = y;
            z  = angle;
        end
        z = z <<< __ANGLE_BITS__;               // add extra angle bits

        // Step 2: start values (with extra guard bits)
        xt = xs;
        yt = ys;
        xt = xt <<< GUARD;
        yt = yt <<< GUARD;

        // Step 3: rotate in small steps
        for (i = 0; i < ITER; i = i + 1) begin
            if (z >= 0) begin
                xn = xt - (yt >>> i);
                yn = yt + (xt >>> i);
                z  = z - atan_table(i);
            end else begin
                xn = xt + (yt >>> i);
                yn = yt - (xt >>> i);
                z  = z + atan_table(i);
            end
            xt = xn;
            yt = yn;
        end

        // Step 4: remove the gain (multiply by 0.60725) and the guard bits
        px = xt * K_INV;
        py = yt * K_INV;
        px = px + ROUND;
        py = py + ROUND;
        x_next = px >>> (16 + GUARD);
        y_next = py >>> (16 + GUARD);
    end

    // -- output register -----------------------------------------------------
    always @(posedge clk) begin
        if (rst) begin
            x_out <= 0;
            y_out <= 0;
        end else begin
            x_out <= x_next;
            y_out <= y_next;
        end
    end

endmodule
"""

    verilog = (
        template
        .replace("__MODULE__",     module_name)
        .replace("__DW__",         str(data_width))
        .replace("__ITER__",       str(CORDIC_ITERATIONS))
        .replace("__ANGLE_BITS__", str(CORDIC_ANGLE_BITS))
        .replace("__TABLE__",      "\n".join(_atan_table_lines()))
    )
    return module_name, verilog


def cordic_instantiation(
    instance_name: str,
    data_width:    int = 16,
    x_src:         str = "0",
    y_src:         str = "0",
    angle_src:     str = "0",
    x_out_wire:    str = "",
    y_out_wire:    str = "",
) -> str:
    """Return the Verilog instantiation string for a cordic_<instance_name> module."""
    module_name = f"cordic_{instance_name}"
    x_conn      = x_out_wire if x_out_wire else f"{instance_name}_x_out"
    y_conn      = y_out_wire if y_out_wire else f"{instance_name}_y_out"

    return "\n".join([
        f"    {module_name} #(",
        f"        .DATA_WIDTH({data_width})",
        f"    ) {instance_name} (",
        f"        .clk   (clk),",
        f"        .rst   (rst),",
        f"        .x     ({x_src}),",
        f"        .y     ({y_src}),",
        f"        .angle ({angle_src}),",
        f"        .x_out ({x_conn}),",
        f"        .y_out ({y_conn})",
        f"    );",
    ])
